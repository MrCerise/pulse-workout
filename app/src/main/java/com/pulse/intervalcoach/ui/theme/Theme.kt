@Immutable
data class PulseColors(
    val isDark: Boolean,
    val background: Color,
    val surface: Color,
    val surfaceRaised: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val outline: Color,
    val work: Color,
    val rest: Color,
    val prepare: Color,
    val cooldown: Color,
    val destructive: Color,
    val onAccent: Color,
    val trueBlack: Boolean = false,
) {
    /** Colour used for a phase's fill (or its label, when [asFill] is false). */
    fun phaseColor(kind: PhaseKind, asFill: Boolean = true): Color = when (kind) {
        PhaseKind.WORK, PhaseKind.WARM_UP -> work
        PhaseKind.REST -> rest
        PhaseKind.TRANSITION -> rest
        PhaseKind.PREPARE -> prepare
        PhaseKind.COOLDOWN -> cooldown
        PhaseKind.CUSTOM -> textSecondary
    }.let { if (asFill || isDark) it else darkenForText(it) }

    private fun darkenForText(color: Color): Color = color

    /** Text colour that is legible on top of the given accent fill. */
    val onPhase: Color get() = onAccent
}

