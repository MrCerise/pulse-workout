fun pulseTypography(): Typography {
    val base = Typography()
    return base.copy(
        displayLarge = base.displayLarge.copy(fontFeatureSettings = "tnum", fontWeight = FontWeight.Bold),
        displayMedium = base.displayMedium.copy(fontFeatureSettings = "tnum", fontWeight = FontWeight.Bold),
        displaySmall = base.displaySmall.copy(fontFeatureSettings = "tnum", fontWeight = FontWeight.SemiBold),
        headlineMedium = base.headlineMedium.copy(fontWeight = FontWeight.SemiBold),
        headlineSmall = base.headlineSmall.copy(fontWeight = FontWeight.SemiBold),
        titleLarge = base.titleLarge.copy(fontWeight = FontWeight.SemiBold),
        labelLarge = base.labelLarge.copy(fontWeight = FontWeight.SemiBold, letterSpacing = 0.5.sp),
        labelSmall = base.labelSmall.copy(letterSpacing = 0.8.sp),
    )
}

@Composable
fun PulseTheme(
    themeMode: ThemeMode,
    dynamicColor: Boolean,
    highContrast: Boolean,
    reducedMotion: Boolean,
    content: @Composable () -> Unit,
) {
    val systemDark = isSystemInDarkTheme()
    val dark = when (themeMode) {
        ThemeMode.SYSTEM -> systemDark
        ThemeMode.LIGHT -> false
        ThemeMode.DARK, ThemeMode.TRUE_BLACK -> true
    }
    val trueBlack = themeMode == ThemeMode.TRUE_BLACK
    val colors = pulseColors(dark = dark, trueBlack = trueBlack, highContrast = highContrast)
    val colorScheme = colors.toMaterialScheme(dynamicColor)
    CompositionLocalProvider(
        LocalPulseColors provides colors,
        LocalPulseDimens provides PulseDimens(),
        LocalPulseMotion provides PulseMotion(reducedMotion),
    ) {
        MaterialTheme(colorScheme = colorScheme, typography = pulseTypography(), content = content)
    }
}

enum class ThemeMode { SYSTEM, LIGHT, DARK, TRUE_BLACK }

fun pulseColors(dark: Boolean, trueBlack: Boolean, highContrast: Boolean): PulseColors {
    return if (dark) {
        PulseColors(
            isDark = true,
            background = if (trueBlack) PulsePalette.TrueBlack else PulsePalette.Ink,
            surface = if (trueBlack) PulsePalette.TrueBlackSurface else PulsePalette.Surface,
            surfaceRaised = if (trueBlack) Color(0xFF14141A) else PulsePalette.SurfaceRaised,
            textPrimary = if (highContrast) PulsePalette.HighContrastText else PulsePalette.TextPrimary,
            textSecondary = if (highContrast) PulsePalette.HighContrastSecondary else PulsePalette.TextSecondary,
            outline = if (highContrast) Color(0xFF6B7899) else PulsePalette.Outline,
            work = if (highContrast) Color(0xFFC7F87C) else PulsePalette.Work,
            rest = if (highContrast) Color(0xFF8BE6F7) else PulsePalette.Rest,
            prepare = if (highContrast) Color(0xFFFFD79A) else PulsePalette.Prepare,
            cooldown = if (highContrast) Color(0xFFCBBDFF) else PulsePalette.Cooldown,
            destructive = PulsePalette.Destructive,
            onAccent = PulsePalette.OnAccent,
            trueBlack = trueBlack,
        )
    } else {
        PulseColors(
            isDark = false,
            background = PulsePalette.LightBackground,
            surface = PulsePalette.LightSurface,
            surfaceRaised = PulsePalette.LightSurfaceRaised,
            textPrimary = if (highContrast) Color(0xFF000000) else PulsePalette.LightTextPrimary,
            textSecondary = if (highContrast) Color(0xFF2A3247) else PulsePalette.LightTextSecondary,
            outline = PulsePalette.LightOutline,
            work = PulsePalette.WorkLight,
            rest = PulsePalette.RestLight,
            prepare = PulsePalette.PrepareLight,
            cooldown = PulsePalette.CooldownLight,
            destructive = PulsePalette.DestructiveLight,
            onAccent = Color.White,
        )
    }
}

/**
 * Material colour scheme for navigation chrome. Dynamic colour (API 31+) only feeds the shell —
 * interval phase colours stay semantic so a phase never changes meaning because of a wallpaper.
 */
fun PulseColors.toMaterialScheme(dynamicColor: Boolean): ColorScheme {
    val base = if (isDark) {
        darkColorScheme(
            primary = work,
            onPrimary = onAccent,
            secondary = rest,
            onSecondary = onAccent,
            tertiary = cooldown,
            onTertiary = onAccent,
            error = destructive,
            onError = onAccent,
            background = background,
            onBackground = textPrimary,
            surface = surface,
            onSurface = textPrimary,
            surfaceVariant = surfaceRaised,
            onSurfaceVariant = textSecondary,
            outline = outline,
            outlineVariant = outline,
        )
    } else {
        lightColorScheme(
            primary = work,
            onPrimary = onAccent,
            secondary = rest,
            onSecondary = onAccent,
            tertiary = cooldown,
            onTertiary = onAccent,
            error = destructive,
            onError = onAccent,
            background = background,
            onBackground = textPrimary,
            surface = surface,
            onSurface = textPrimary,
            surfaceVariant = surfaceRaised,
            onSurfaceVariant = textSecondary,
            outline = outline,
            outlineVariant = outline,
        )
    }
    if (!dynamicColor) return base
    return base
}

