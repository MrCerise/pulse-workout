// --- WCAG helpers (also used by the contrast report generator) --------------------------------

fun relativeLuminance(color: Color): Double {
    fun channel(v: Float): Double {
        val c = v.toDouble()
        return if (c <= 0.03928) c / 12.92 else ((c + 0.055) / 1.055).pow(2.4)
    }
    return 0.2126 * channel(color.red) + 0.7152 * channel(color.green) + 0.0722 * channel(color.blue)
}

fun contrastRatio(a: Color, b: Color): Double {
    val la = relativeLuminance(a)
    val lb = relativeLuminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)
}

/**
 * Text colour that stays readable on an arbitrary tint: white on dark fills, ink on light ones.
 * Used wherever a caller supplies its own background tint.
 */
fun legibleOn(background: Color): Color =
    if (relativeLuminance(background) > 0.35) Color(0xFF0A0E1C) else Color(0xFFF6F8FE)
