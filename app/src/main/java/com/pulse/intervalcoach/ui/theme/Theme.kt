@Immutable
data class PulseColors(
    val isDark: Boolean,
    val background: Color,
    val surface: Color,
    val surfaceRaised: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val outline: Color,
    val work: Color,
    val rest: Color,
    val prepare: Color,
    val cooldown: Color,
    val destructive: Color,
    val onAccent: Color,
    val trueBlack: Boolean = false,
    /** Set when the user turned on the high-contrast switch. */
    val highContrast: Boolean = false,
    // Material tonal ramp. Defaults mirror the dark palette so a hand-built PulseColors
    // (previews, tests, the first frame) is still coherent.
    val surfaceContainerLowest: Color = PulsePalette.DarkContainerLowest,
    val surfaceContainerLow: Color = PulsePalette.DarkContainerLow,
    val surfaceContainer: Color = PulsePalette.Surface,
    val surfaceContainerHigh: Color = PulsePalette.DarkContainerHigh,
    val surfaceContainerHighest: Color = PulsePalette.DarkContainerHighest,
    val surfaceDim: Color = PulsePalette.DarkSurfaceDim,
    val surfaceBright: Color = PulsePalette.DarkSurfaceBright,
    val outlineVariant: Color = PulsePalette.DarkOutlineVariant,
    val primaryContainer: Color = PulsePalette.DarkPrimaryContainer,
    val onPrimaryContainer: Color = PulsePalette.DarkOnPrimaryContainer,
    val secondaryContainer: Color = PulsePalette.DarkSecondaryContainer,
    val onSecondaryContainer: Color = PulsePalette.DarkOnSecondaryContainer,
    val tertiaryContainer: Color = PulsePalette.DarkTertiaryContainer,
    val onTertiaryContainer: Color = PulsePalette.DarkOnTertiaryContainer,
    val errorContainer: Color = PulsePalette.DarkErrorContainer,
    val onErrorContainer: Color = PulsePalette.DarkOnErrorContainer,
    val inverseSurface: Color = PulsePalette.TextPrimary,
    val inverseOnSurface: Color = PulsePalette.Ink,
    val inversePrimary: Color = Color(0xFF567F12),
) {
    /** Colour used for a phase's fill (or its label, when [asFill] is false). */
    fun phaseColor(kind: PhaseKind, asFill: Boolean = true): Color = when (kind) {
        PhaseKind.WORK, PhaseKind.WARM_UP -> work
        PhaseKind.REST -> rest
        PhaseKind.TRANSITION -> rest
        PhaseKind.PREPARE -> prepare
        PhaseKind.COOLDOWN -> cooldown
        PhaseKind.CUSTOM -> textSecondary
    }

    /** Neutral fill for labels that are *not* phases (workout type, counts, "starter"). */
    val neutralFill: Color get() = surfaceContainerHigh

    /** Text colour that sits on top of [neutralFill]. */
    val onNeutralFill: Color get() = textPrimary

    /** Subtle track behind progress rings and scrubbers — visible, never competing with the fill. */
    val track: Color get() = outline.copy(alpha = if (isDark) 0.28f else 0.24f)

    /** Tint used behind an active bottom-bar item / highlighted card. */
    val activeGlow: Color get() = work.copy(alpha = if (isDark) 0.14f else 0.18f)

    /**
     * Soft vertical wash of a phase colour, fading to nothing — the v1.3 immersive player
     * background. Deliberately subtle so the timer, not the decoration, is the focal point.
     */
    fun phaseWash(kind: PhaseKind): Brush = Brush.verticalGradient(
        colors = listOf(
            phaseColor(kind).copy(alpha = if (isDark) 0.22f else 0.10f),
            phaseColor(kind).copy(alpha = 0f),
        ),
    )

    /** The brand gradient (work lime → rest cyan) for hero elements. */
    val brandGradient: Brush
        get() = Brush.linearGradient(listOf(work, rest))

    /** Gradient ring stroke for the player timer. */
    fun ringGradient(kind: PhaseKind): Brush {
        val phase = phaseColor(kind)
        return Brush.sweepGradient(listOf(phase, phase.copy(alpha = 0.35f), phase))
    }
}

