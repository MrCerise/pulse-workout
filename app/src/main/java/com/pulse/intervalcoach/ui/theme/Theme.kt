/**
 * PULSE design tokens — v1.3 "Aurora" edition.
 *
 * The v1.3 rework keeps the brand's two meanings (interval ring + pulse trace) but moves the
 * interface to a more expressive, 2026-style system:
 *
 *  - a deeper, more saturated midnight navy with a full tonal ramp, so cards, dialogs and menus
 *    sit in soft steps of the same hue instead of floating in one flat shade;
 *  - brighter, higher-glow interval colours (lime / cyan / amber / violet) that read at a glance
 *    from across a room;
 *  - generous radii (28 dp cards, pill controls) and gradient washes for the immersive player;
 *  - expressive typography: heavier display weights with tabular figures so the countdown never
 *    shifts width.
 *
 * Contrast for every token pairing is measured in docs/CONTRAST.md (generated by
 * scripts/contrast_check.py from the same hex values). Rules that keep the UI legible:
 *  - interval colours are *fills* for phase chips/tiles and are always paired with [onAccent];
 *  - on dark surfaces text uses [PulseColors.textPrimary]/[textSecondary], never a raw accent;
 *  - Material components (dialogs, menus, the bottom bar, chips, switches) read the tonal ramp in
 *    [PulseColors.surfaceContainer]…[surfaceContainerHighest], so no Material3 default ever paints
 *    the stock purple-grey baseline on top of the navy palette.
 */

